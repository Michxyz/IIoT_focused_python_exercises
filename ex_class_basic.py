#1. Create a class called TopicBuilder to generate consistent UNS-style MQTT topics.
#Goal: Encapsulate MQTT topic naming rules inside a class so the rest of your code can 
# call one clean interface. 
#--------------Requirements: -------------------------------------------
""" 
Attributes (instance data)
site: str
line: str
cell: str
These represent the fixed “location” part of the topic.

Methods:
1) build(tag) 
Return a topic string in this format:
site/line/cell/tag
Normalization rules (apply to every segment, including tag):
-   convert to lowercase
-   trim spaces around the text
-   replace internal spaces " " with "_"

2) with_cell(new_cell) 
Update the object's cell attribute with new_cell (also normalized).
This simulates moving the same logic to a different cell without creating a new instance.
"""
print("------------------------Exercise 1: Topic Builder --------------------------\n")

class TopicBuilder: 
    """ Generate  consistent UNS-style MQTT topics"""
    def __init__(self, site: str, line: str, cell: str):
        """ Initialize a TopicBuilder with normalized UNS topic segments (site, line, cell).
All segments are stored in a consistent format: lowercase, trimmed, and with
internal spaces replaced by underscores."""
        self.site = site
        self.line = line
        self.cell = cell
        #Normalize segments:
        self.site = self.site.lower().strip().replace(" ", "_")
        self.line = self.line.lower().strip().replace(" ", "_")
        self.cell = self.cell.lower().strip().replace(" ", "_") 

    def build(self, tag: str) -> str:
        """ 
        Build and return a normalized UNS-style MQTT topic: site/line/cell/tag.
        The tag is normalized (lowercase, trimmed, spaces -> '_') before joining.
        """
        tag = tag.lower().strip().replace(" ", "_")
        temporal_list: list[str] = [self.site, self.line, self.cell, tag]
        return  "/".join(temporal_list)
    
    def with_cell(self, new_cell: str) -> None:
        """ 
        Update the object's cell attribute with new_cell (also normalized).
        """
        self.cell = new_cell.lower().strip().replace(" ", "_")
        

