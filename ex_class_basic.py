#Goal: Separate data (alarm event) from decision logic (policy), without using inheritance.

print("----------------------Exercise 2: AlarmEvent + AlarmPolicy  -------------------------\n")

class AlarmEvent: 
    """Represents an alarm generated by an IIoT device or system."""

    def __init__(self, code: str, severity: int, ts: int, source_topic: str):
        self.code = code
        self.severity = severity
        self.ts = ts
        self.source_topic = source_topic
    
    def is_critical(self) -> bool:
        """Return True if the alarm severity is above the critical threshold. """
        return self.severity > 3

    def summary(self) -> str:
        """ Return a short text summary of the alarm."""
        return f"Alarm: {self.code} | sev={self.severity} | ts={self.ts} | source={self.source_topic}"

class AlarmPolicy:
    """Defines rules to decide if an alarm requires action or not."""

    def __init__(self, min_severity: int, blocked_codes: set[str]):
        """Initialize the policy with a minimum severity and blocked alarm codes."""
        self.min_severity = min_severity
        self.blocked_codes = blocked_codes
    
    def is_actionable(self, alarm: AlarmEvent) -> bool:
        """Return True if the alarm passes the policy rules."""
        if alarm.severity >= self.min_severity and alarm.code not in self.blocked_codes:
            return True
        else:
            return False
        

#3. ShiftReport: Create a class called ShiftReport to store production data and calculate simple KPIs.
""" 
---Attributes:
shift: str
approved: int
rejected: int
warnings: list[str] — starts empty
---Methods
total() -> int
scrap_rate() -> float
add_warning(msg: str) -> None
as_dict() -> dict
---Rules
If total production is zero, scrap_rate() must return 0.0
In that zero-total case, also add a warning to warnings
Do not print inside methods
---Goal
Practice storing state and encapsulating business logic inside methods.
"""

print("----------------------Exercise 3: ShiftReport  -------------------------\n")

class ShiftReport:

    def __init__(self, shift: str, approved: int, rejected: int):
        self.shift = shift
        self.approved = approved
        self.rejected =  rejected
        self.warnings: list[str] = []

    def total(self) -> int:
        """ Calculate the total of produced units"""
        return self.approved + self.rejected

    def scrap_rate(self) -> float:
        """ Calculate the scrape rate of the total produced units"""
        total_units = self.total() #Create local var

        if total_units == 0:
            self.add_warning("Cannot calculate  scrap rate")
            return 0.0
        
        else: return round(self.rejected / total_units * 100, 2)

    def add_warning(self, msg: str) -> None:
        """This function adds a warning, a string to the warnings list."""
        self.warnings.append(msg)

    def as_dict(self) -> dict:
        """ Return the report data as a dictionary"""
        return {
            'shift': self.shift,
            'approved': self.approved,
            'rejected': self.rejected,
            'scrap_rate': self.scrap_rate(),
            'warnings': self.warnings
        }
